import { expect, test } from '@playwright/test'
import { chatPath, message, prepareChat } from './chat-identity-fixture'

const source = '  **Key directories:**\r\n| Directory | Purpose |\r\n| :--- | ---: |\r\n| `engine/` | **API** |\r\n| `a|b` | escaped \\| pipe |\r\nAfter table\r\n\r\n```ts\r\na|b\r\n\r\nc|d\r\n```\r\n  '

test('assistant table renders semantic formatted cells and copies exact source by keyboard', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  const chat = await prepareChat(page, [message('user-source', source, 'user'), {
    ...message('assistant-source', source), attachments: [{ path: 'report.txt', name: 'report.txt' }],
  }])
  await page.goto(chatPath())
  await chat.socket()
  const response = page.locator('[data-chat-entry="assistant-source"]')
  await expect(response.getByRole('columnheader')).toHaveText(['Directory', 'Purpose'])
  await expect(response.getByRole('cell')).toHaveText(['engine/', 'API', 'a|b', 'escaped | pipe'])
  await expect(response.locator('td strong')).toHaveText('API')
  await expect(response.locator('pre code')).toHaveText('a|b\n\nc|d\n')
  await expect(response.getByRole('button', { name: 'Preview', exact: true })).toBeVisible()
  await expect(page.locator('[data-chat-entry="user-source"] table, [data-chat-entry="user-source"] button')).toHaveCount(0)
  const copy = response.getByRole('button', { name: 'Copy response', exact: true })
  await copy.focus()
  const before = await copy.boundingBox()
  await copy.press('Enter')
  const copied = response.getByRole('button', { name: 'Copied response', exact: true })
  await expect(copied).toBeFocused()
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(source)
  const after = await copied.boundingBox()
  expect([after?.width, after?.height]).toEqual([before?.width, before?.height])
  expect([after?.width, after?.height]).toEqual([44, 44])
})

test('clipboard rejection shows retry feedback without a copied state', async ({ page }) => {
  await page.addInitScript(() => {
    Object.defineProperty(navigator, 'clipboard', { value: { writeText: () => Promise.reject(new DOMException('Denied', 'NotAllowedError')) } })
  })
  const chat = await prepareChat(page, [message('copy-failure', '**Original** source')])
  await page.goto(chatPath())
  await chat.socket()
  const response = page.locator('[data-chat-entry="copy-failure"]')
  await response.getByRole('button', { name: 'Copy response', exact: true }).click()
  await expect(response.getByRole('status')).toHaveText('Could not copy. Try again.')
  await expect(response.getByRole('button', { name: 'Copied response', exact: true })).toHaveCount(0)
  await expect(response.getByRole('button', { name: 'Copy response', exact: true })).toBeEnabled()
})

test('copy success resets after two seconds and another successful click restarts the delay', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  const chat = await prepareChat(page, [message('copy-reset', source)])
  await page.goto(chatPath())
  await chat.socket()
  await page.clock.install({ time: new Date('2030-01-01T00:00:00Z') })
  await page.clock.pauseAt(new Date('2030-01-01T00:00:01Z'))
  const response = page.locator('[data-chat-entry="copy-reset"]')
  await response.getByRole('button', { name: 'Copy response', exact: true }).click()
  const copied = response.getByRole('button', { name: 'Copied response', exact: true })
  await expect(copied).toBeVisible()
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(source)
  await page.clock.runFor(1000)
  await copied.click()
  await expect(copied).toBeVisible()
  await page.clock.runFor(1000)
  await expect(copied).toBeVisible()
  await page.clock.runFor(999)
  await expect(copied).toBeVisible()
  await page.clock.runFor(1)
  await expect(response.getByRole('button', { name: 'Copy response', exact: true })).toHaveAttribute('title', 'Copy response')
  await expect(response.getByRole('status')).toBeEmpty()
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(source)
})

test('streamed assistant copy follows the current source as chunks arrive', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  const chat = await prepareChat(page)
  await page.goto(chatPath())
  const socket = await chat.socket()
  await page.clock.install({ time: new Date('2030-01-01T00:00:00Z') })
  await page.clock.pauseAt(new Date('2030-01-01T00:00:01Z'))
  const turn = '11111111-1111-4111-8111-111111111111'
  socket.route.send(JSON.stringify({ type: 'chunk', turn_id: turn, seq: 0, content: '**First** ' }))
  const live = page.locator('article[aria-live="polite"]')
  await live.getByRole('button', { name: 'Copy response', exact: true }).click()
  await expect(live.getByRole('button', { name: 'Copied response', exact: true })).toBeVisible()
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('**First** ')
  await page.clock.runFor(1000)
  socket.route.send(JSON.stringify({ type: 'chunk', turn_id: turn, seq: 1, content: '\nnext  ' }))
  await live.getByRole('button', { name: 'Copy response', exact: true }).click()
  await expect(live.getByRole('button', { name: 'Copied response', exact: true })).toBeVisible()
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('**First** \nnext  ')
  await page.clock.runFor(1000)
  await expect(live.getByRole('button', { name: 'Copied response', exact: true })).toBeVisible()
  await page.clock.runFor(1000)
  await expect(live.getByRole('button', { name: 'Copy response', exact: true })).toBeVisible()
  await expect(live.getByRole('status')).toBeEmpty()
})
