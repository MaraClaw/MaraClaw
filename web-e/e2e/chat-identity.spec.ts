import { expect, test } from '@playwright/test'
import { accept, chatPath, complete, firstMessage, firstSession, message, prepareChat, submitted } from './chat-identity-fixture'
import { originalAgent } from './session-fencing-fixture'

test('busy polling still recovers a persisted reply without a completion frame', async ({ page }) => {
  // Given
  const old = message('old', 'Already loaded reply')
  const question = message('poll-user', 'Question awaiting reply', 'user')
  const reply = message('poll-reply', 'Recovered by busy polling')
  const chat = await prepareChat(page, [old])
  await page.clock.install({ time: new Date('2030-01-01T00:00:00Z') })
  await page.goto(chatPath())
  const socket = await chat.socket()
  await page.clock.pauseAt(new Date('2030-01-01T01:00:00Z'))
  await page.getByPlaceholder(`Message ${originalAgent.name}…`).fill(question.content)
  await page.getByPlaceholder(`Message ${originalAgent.name}…`).press('Enter')
  await expect.poll(() => socket.sent.length).toBe(1)
  await expect(page.locator('[aria-busy]')).toHaveAttribute('aria-busy', 'true')
  chat.setHistory([{ ...question, client_submission_id: submitted(socket).client_submission_id }, reply])
  const refreshed = page.waitForEvent('requestfinished', {
    predicate: (request) => new URL(request.url()).pathname.endsWith(`/sessions/${firstSession}/messages`),
  })
  // When
  await page.clock.runFor(5_000)
  await refreshed
  await page.clock.runFor(100)
  // Then
  await expect(page.locator('article')).toHaveText([old.content, question.content, reply.content])
  await expect(page.locator('[aria-busy]')).toHaveAttribute('aria-busy', 'false')
})

test('lost acceptance survives reconnect and socket effect recreation with the same frozen submission', async ({ page }) => {
  const chat = await prepareChat(page)
  await page.goto(chatPath())
  const first = await chat.socket()
  await page.getByRole('textbox', { name: `Message ${originalAgent.name}` }).fill('One logical question')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect.poll(() => first.sent.length).toBe(1)
  const envelope = submitted(first)
  first.route.close({ code: 1006 })
  const reconnected = await chat.socket(1)
  await expect.poll(() => reconnected.sent).toEqual(first.sent)
  chat.setOnboarded(true)
  reconnected.route.send(JSON.stringify({ type: 'onboarded' }))
  const recreated = await chat.socket(2)
  await expect.poll(() => recreated.sent).toEqual(first.sent)
  accept(recreated, envelope.client_submission_id)
  chat.setHistory([{ ...message(firstMessage, envelope.content, 'user'), client_submission_id: envelope.client_submission_id }])
  complete(recreated.route, message('reply', 'One reply'))
  await expect(page.locator('article')).toHaveText(['One logical question', 'One reply'])
  recreated.route.close({ code: 1006 })
  const acceptedReconnect = await chat.socket(3)
  expect(acceptedReconnect.sent).toEqual([])
  expect(new Set(chat.tickets.map((ticket) => ticket.ticket)).size).toBe(4)
})

test('unknown acceptance offers an explicit same-ID text retry without replacing the current draft', async ({ page }, testInfo) => {
  const chat = await prepareChat(page)
  await page.clock.install()
  await page.goto(chatPath())
  const socket = await chat.socket()
  const composer = page.getByRole('textbox', { name: `Message ${originalAgent.name}` })
  await composer.fill('Keep the original payload')
  await composer.press('Enter')
  await expect.poll(() => socket.sent.length).toBe(1)
  await composer.fill('A separate unfinished draft')
  await page.clock.fastForward(90_000)
  await expect(page.getByText('Acceptance not confirmed.', { exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('acceptance-unknown.png'), fullPage: true })
  await page.getByRole('button', { name: 'Retry this message', exact: true }).click()
  await expect.poll(() => socket.sent.length).toBe(2)
  expect(socket.sent[1]).toBe(socket.sent[0])
  await expect(composer).toHaveValue('A separate unfinished draft')
  accept(socket, submitted(socket).client_submission_id)
  await expect(page.getByRole('button', { name: 'Retry this message', exact: true })).toHaveCount(0)
})

test('accepted but slow replies never offer a duplicate send', async ({ page }, testInfo) => {
  const chat = await prepareChat(page)
  await page.clock.install()
  await page.goto(chatPath())
  const socket = await chat.socket()
  const composer = page.getByRole('textbox', { name: `Message ${originalAgent.name}` })
  await composer.fill('Wait for the accepted reply')
  await composer.press('Enter')
  await expect.poll(() => socket.sent.length).toBe(1)
  accept(socket, submitted(socket).client_submission_id)
  await page.clock.fastForward(90_000)
  await expect(page.getByText('Accepted. The reply is taking longer than usual. No need to send again.', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Retry this message', exact: true })).toHaveCount(0)
  await composer.fill('Do not duplicate the accepted turn')
  await expect(page.getByRole('button', { name: 'Send', exact: true })).toBeDisabled()
  expect(socket.sent).toHaveLength(1)
  await page.screenshot({ path: testInfo.outputPath('accepted-slow-desktop.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.evaluate(() => document.documentElement.classList.add('dark'))
  await page.screenshot({ path: testInfo.outputPath('accepted-slow-phone-dark.png'), fullPage: true })
})

test('terminal access denial cannot retry through a stopped sender', async ({ page }, testInfo) => {
  const chat = await prepareChat(page)
  await page.goto(chatPath())
  const socket = await chat.socket()
  const composer = page.getByRole('textbox', { name: `Message ${originalAgent.name}` })
  await composer.fill('Keep this rejected submission')
  await composer.press('Enter')
  await expect.poll(() => socket.sent.length).toBe(1)
  socket.route.send(JSON.stringify({ type: 'turn_rejected', client_submission_id: submitted(socket).client_submission_id,
    reason: 'enqueue_failed', content: 'Queue unavailable.' }))
  const retry = page.getByRole('button', { name: 'Retry this message', exact: true })
  await expect(retry).toBeEnabled()

  socket.route.close({ code: 4003 })

  await expect(retry).toBeDisabled()
  await composer.fill('Do not enqueue into a stopped connection')
  await composer.press('Enter')
  await expect(page.locator('[aria-busy]')).toHaveAttribute('aria-busy', 'false')
  await expect(page.getByRole('button', { name: 'Send', exact: true })).toBeDisabled()
  await expect(page.getByLabel('Attach a file', { exact: true })).toBeDisabled()
  expect(socket.sent).toHaveLength(1)
  await page.screenshot({ path: testInfo.outputPath('terminal-stopped.png'), fullPage: true })
})

test('file rejection retries the exact uploaded envelope after effect recreation without uploading again', async ({ page }, testInfo) => {
  const chat = await prepareChat(page)
  let uploads = 0
  await page.route('**/api/chat/upload', (route) => {
    uploads++
    return route.fulfill({ json: { filename: 'notes.txt', extracted_text: 'Frozen extracted notes', workspace_path: 'uploads/notes.txt' } })
  })
  await page.goto(chatPath())
  const socket = await chat.socket()
  await page.getByLabel('Attach a file', { exact: true }).setInputFiles({ name: 'notes.txt', mimeType: 'text/plain', buffer: Buffer.from('file bytes') })
  await expect.poll(() => socket.sent.length).toBe(1)
  const envelope = submitted(socket)
  expect(envelope).toMatchObject({ content: 'Frozen extracted notes', display_content: 'notes.txt', file_name: 'notes.txt' })
  socket.route.close({ code: 1006 })
  const reconnected = await chat.socket(1)
  await expect.poll(() => reconnected.sent).toEqual(socket.sent)
  reconnected.route.send(JSON.stringify({ type: 'turn_rejected', client_submission_id: envelope.client_submission_id, reason: 'enqueue_failed', content: 'Queue unavailable.' }))
  await expect(page.getByRole('button', { name: 'Retry this message', exact: true })).toBeVisible()
  chat.setOnboarded(true)
  reconnected.route.send(JSON.stringify({ type: 'onboarded' }))
  const recreated = await chat.socket(2)
  expect(recreated.sent).toEqual([])
  await page.screenshot({ path: testInfo.outputPath('file-retry.png'), fullPage: true })
  await page.getByRole('button', { name: 'Retry this message', exact: true }).click()
  await expect.poll(() => recreated.sent).toEqual(socket.sent)
  expect(uploads).toBe(1)
  accept(recreated, envelope.client_submission_id)
  chat.setHistory([{ ...message(firstMessage, 'notes.txt', 'user'), file_name: 'notes.txt', client_submission_id: envelope.client_submission_id }])
  complete(recreated.route, message('file-reply', 'Read the notes'))
  await expect(page.locator('article')).toHaveText(['notes.txt', 'Read the notes'])
})

test('equal text remains two logical submissions and legacy equal text never consumes an optimistic row', async ({ page }) => {
  const oldUser = message('old-user', 'Same question', 'user')
  const oldReply = message('old-reply', 'Earlier answer')
  const chat = await prepareChat(page, [oldUser, oldReply])
  await page.goto(chatPath())
  const socket = await chat.socket()
  const composer = page.getByRole('textbox', { name: `Message ${originalAgent.name}` })
  await composer.fill('Same question')
  await composer.press('Enter')
  await expect.poll(() => socket.sent.length).toBe(1)
  const envelope = submitted(socket)
  chat.setHistory([oldUser, oldReply, { ...message(firstMessage, 'Same question', 'user'), client_submission_id: envelope.client_submission_id }])
  complete(socket.route, message('new-reply', 'New answer'))
  await expect(page.locator('article')).toHaveText(['Same question', 'Earlier answer', 'Same question', 'New answer'])
  await composer.fill('Same question')
  await composer.press('Enter')
  await expect.poll(() => socket.sent.length).toBe(2)
  expect(submitted(socket, 1).client_submission_id).not.toBe(envelope.client_submission_id)
  await expect(page.locator('article').filter({ hasText: /^Same question$/ })).toHaveCount(3)
})
