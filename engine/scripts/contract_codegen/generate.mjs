import { readFile, writeFile } from "node:fs/promises";
import { parseArgs } from "node:util";
import { pathToFileURL } from "node:url";
import { ContractError, parseDocument } from "./document.mjs";
import { compileDocument } from "./compiler.mjs";

export function generate(input) {
  return "// Generated by engine/scripts/contract_codegen/generate.mjs; do not edit.\n" +
    compileDocument(parseDocument(input));
}

export async function main(args) {
  const { values } = parseArgs({ args, options: {
    input: { type: "string" }, output: { type: "string" }, check: { type: "boolean", default: false },
  } });
  if (!values.input || !values.output) throw new ContractError("arguments", "--input and --output are required");
  const content = generate(JSON.parse(await readFile(values.input, "utf8")));
  if (values.check) {
    let current;
    try { current = await readFile(values.output, "utf8"); }
    catch (error) {
      if (!(error instanceof Error) || !("code" in error) || error.code !== "ENOENT") throw error;
    }
    if (current !== content) throw new ContractError(values.output, "stale generated contract; regenerate without --check");
  } else {
    await writeFile(values.output, content, "utf8");
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try { await main(process.argv.slice(2)); }
  catch (error) {
    if (!(error instanceof Error)) throw error;
    console.error(error.message);
    process.exitCode = 1;
  }
}
